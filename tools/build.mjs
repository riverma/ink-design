#!/usr/bin/env node
/* Flatten the @import chain into one shippable file, and sync the docs
   site's copy of it and of the fonts. */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const order = [...readFileSync('src/ink.css', 'utf8').matchAll(/@import url\("([^"]+)"\)/g)].map((m) => m[1]);
const version = JSON.parse(readFileSync('package.json', 'utf8')).version;

const css = `/*! Ink Design System v${version} — Paper + Night
 *  MIT. Fonts are SIL OFL-1.1; ship fonts/OFL-*.txt alongside them.
 *  Generated by tools/build.mjs — edit src/, not this file. */\n`
  + order.map((p) => `\n/* ===== ${p} ===== */\n${readFileSync(`src/${p}`, 'utf8').trimEnd()}`).join('\n') + '\n';

if (/@import\s+url\(\s*['"]?https?:/i.test(css)) {
  console.error('FAIL — a remote @import reached dist/.');
  process.exit(1);
}

mkdirSync('dist', { recursive: true });
writeFileSync('dist/ink.css', css);
writeFileSync('dist/CHECKSUMS', `${createHash('sha256').update(css).digest('hex')}  ink.css\n`);
console.log(`dist/ink.css  ${css.length} bytes`);

/* The docs copy uses relative font urls so it works from any path. */
mkdirSync('docs/fonts', { recursive: true });
writeFileSync('docs/ink.css', css.replace(/url\("\/fonts\//g, 'url("fonts/'));
for (const f of readdirSync('fonts')) copyFileSync(`fonts/${f}`, `docs/fonts/${f}`);
console.log(`docs/ink.css + docs/fonts/ (${readdirSync('fonts').length} files) synced`);
